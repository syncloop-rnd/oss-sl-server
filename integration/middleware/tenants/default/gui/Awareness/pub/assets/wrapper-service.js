function prepareAgentWrapperService(AgentId, AgentName) {
    let wrapperService = WRAPPER_SERVICE_JSON;
    wrapperService.latest.api[0].children[0].children[0].data.createList = [];

    wrapperService.latest.api[0].children[0].children[0].data.createList.push({
        path: "agentId",
        value: AgentId,
        id: generateUUID(),
        typePath: 'string'
    });

    wrapperService.latest.api[0].children[0].children[0].data.createList.push({
        path: "agentName",
        value: AgentName,
        id: generateUUID(),
        typePath: 'string'
    });

    /**
     *
     * @returns {string}
     */
    function generateUUID() {
        var d = new Date().getTime();
        var d2 = (performance && performance.now && (performance.now() * 1000)) || 0;
        return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, function(c) {
            var r = Math.random() * 16;
            if (d > 0) {
                r = (d + r) % 16 | 0;
                d = Math.floor(d / 16);
            } else {
                r = (d2 + r) % 16 | 0;
                d2 = Math.floor(d2 / 16);
            }
            return (c === 'x' ? r : (r & 0x3 | 0x8)).toString(16);
        });
    }

    return wrapperService;
}

/**
 *
 * @param serviceJson
 * @param consumerArray
 * @returns {*}
 */
function addConsumerInAgentWrapperService(serviceJson, consumerArray) {

    if (!serviceJson || !Array.isArray(consumerArray)) {
        return serviceJson;
    }

    const consumers = consumerArray.join(",");
    serviceJson.consumers = consumers;

    return serviceJson;
}

/**
 *
 * @param serviceJson
 * @param consumerArray
 * @returns {{consumers}|*}
 */
function removeConsumerFromAgentWrapperService(serviceJson, consumerArray) {


    if (!serviceJson) {
        return serviceJson;
    }

    let consumersToRemove = (consumerArray || "")
        .toString()
        .split(",")
        .map(function (item) {
            return item.trim();
        })
        .filter(function (item) {
            return item !== "";
        });

    if (consumersToRemove.length === 0) {
        return serviceJson;
    }

    serviceJson.consumers = (serviceJson.consumers || "")
        .toString()
        .split(",")
        .map(function (item) {
            return item.trim();
        })
        .filter(function (item) {
            return item !== "" && !consumersToRemove.includes(item);
        })
        .toString();

    return serviceJson;
}
